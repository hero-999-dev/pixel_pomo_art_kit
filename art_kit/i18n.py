STRINGS = {EN: _EN, TR: _TR, PL: _PL, DE: _DE}

_current = EN


def set_language(code):
    global _current
    _current = code if code in STRINGS else EN
    return _current


def language():
    return _current


def t(key, **kw):
    table = STRINGS.get(_current) or _EN
    text = table.get(key)
    if text is None:
        text = _EN.get(key, key)
    return text.format(**kw) if kw else text


def font_for(key):
    """Chrome buttons keep their box; a long translation uses a smaller font."""
    if _current == EN or key not in _TIGHT:
        return theme.FONT_BOLD
    return theme.FONT_SMALL
