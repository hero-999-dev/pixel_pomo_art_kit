STRINGS = {EN: _EN, TR: _TR, PL: _PL, DE: _DE}

_current = EN


def set_language(code):
    global _current
    _current = code if code in STRINGS else EN
    return _current


def language():
    return _current


def t(key, **kw):
    table = STRINGS.get(_current) or _EN
    text = table.get(key)
    if text is None:
        text = _EN.get(key, key)
    return text.format(**kw) if kw else text


def font_for(_key=None):
    """The font a chrome button gets when its text is re-translated.

    Always the kit's one family, always bold (#v2.8.0). Up to #v2.7.0 this
    returned `theme.FONT_SMALL` for a long translation, which is neither
    bold nor the same rendering weight, so every non-English UI looked like
    it had swapped typeface. Making a long label fit is a size-only decision
    and it belongs to the widget that knows its own frozen box, so a pinned
    `theme.Button` overrides this with `theme.fit_bold` the moment the text
    lands."""
    return theme.FONT_BOLD
